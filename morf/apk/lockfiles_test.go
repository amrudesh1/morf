// buildTestComponents builds a slice with the given names and no versions, to
// simulate components detected by binary/runtime analysis before lockfile
// enrichment.
func buildTestComponents(names ...string) []models.SBOMComponent {
	out := make([]models.SBOMComponent, 0, len(names))
	for _, name := range names {
		out = append(out, models.NewRuntimeComponent(name, nil))
	}
	return out
}

// TestEnrichFromAndroidLockfiles_PubspecLock verifies that a component matching
// a pubspec.lock entry gets its Version set and purl upgraded to pkg:pub.
func TestEnrichFromAndroidLockfiles_PubspecLock(t *testing.T) {
	jc := jobCtxForDir(t, "enrich-pub")

	// Write a pubspec.lock into the workspace root.
	lockContent := `packages:
  http:
    dependency: "direct main"
    description:
      name: http
      url: "https://pub.dev"
    source: hosted
    version: "1.2.2"
  provider:
    dependency: "direct main"
    description:
      name: provider
      url: "https://pub.dev"
    source: hosted
    version: "6.1.2"
sdks:
  dart: ">=3.0.0 <4.0.0"
`
	if err := os.WriteFile(filepath.Join(jc.Workspace, "pubspec.lock"), []byte(lockContent), 0o600); err != nil {
		t.Fatalf("write pubspec.lock: %v", err)
	}

	// A Flutter runtime component was detected via binary analysis (no version).
	initial := []models.SBOMComponent{
		models.NewRuntimeComponent("Flutter", []string{"lib/arm64-v8a/libflutter.so"}),
	}

	enriched := EnrichFromAndroidLockfiles(jc, initial)

	// The Flutter runtime component should be unchanged (no flutter entry in our fixture).
	var flutter *models.SBOMComponent
	for i := range enriched {
		if enriched[i].Name == "Flutter" {
			flutter = &enriched[i]
		}
	}
	if flutter == nil {
		t.Fatal("Flutter component missing after enrichment")
	}
	if flutter.Version != "" {
		t.Errorf("Flutter.Version = %q, want empty (not in pubspec.lock)", flutter.Version)
	}

	// New components should have been added for http and provider.
	byName := indexByName(enriched)
	httpC, ok := byName["http"]
	if !ok {
		t.Fatal("http component missing; expected new component from pubspec.lock")
	}
	if httpC.Version != "1.2.2" {
		t.Errorf("http.Version = %q, want 1.2.2", httpC.Version)
	}
	if !strings.HasPrefix(httpC.Purl, "pkg:pub/http@") {
		t.Errorf("http.Purl = %q, want pkg:pub/http@...", httpC.Purl)
	}

	provC, ok := byName["provider"]
	if !ok {
		t.Fatal("provider component missing; expected new component from pubspec.lock")
	}
	if provC.Version != "6.1.2" {
		t.Errorf("provider.Version = %q, want 6.1.2", provC.Version)
	}
}

// TestEnrichFromAndroidLockfiles_PackageLock verifies package-lock.json enrichment.
func TestEnrichFromAndroidLockfiles_PackageLock(t *testing.T) {
	jc := jobCtxForDir(t, "enrich-npm")

	pkgLock := `{
  "lockfileVersion": 2,
  "packages": {
    "": { "name": "app" },
    "node_modules/react-native": { "version": "0.73.6" },
    "node_modules/lodash": { "version": "4.17.21" }
  }
}`
	if err := os.WriteFile(filepath.Join(jc.Workspace, "package-lock.json"), []byte(pkgLock), 0o600); err != nil {
		t.Fatalf("write package-lock.json: %v", err)
	}

	// Simulate a React Native runtime component detected from .so files.
	initial := []models.SBOMComponent{
		models.NewRuntimeComponent("React Native", []string{"lib/arm64-v8a/libhermes.so"}),
	}
	enriched := EnrichFromAndroidLockfiles(jc, initial)

	byName := indexByName(enriched)

	// react-native should be a new component.
	rnC, ok := byName["react-native"]
	if !ok {
		t.Fatal("react-native component missing from enriched list")
	}
	if rnC.Version != "0.73.6" {
		t.Errorf("react-native.Version = %q, want 0.73.6", rnC.Version)
	}
	if !strings.HasPrefix(rnC.Purl, "pkg:npm/react-native@") {
		t.Errorf("react-native.Purl = %q, want pkg:npm/react-native@...", rnC.Purl)
	}

	lodashC, ok := byName["lodash"]
	if !ok {
		t.Fatal("lodash component missing from enriched list")
	}
	if lodashC.Version != "4.17.21" {
		t.Errorf("lodash.Version = %q, want 4.17.21", lodashC.Version)
	}

	// The React Native runtime component should still be present.
	if _, ok := byName["React Native"]; !ok {
		t.Error("React Native runtime component should not have been removed")
	}
}

// TestEnrichFromAndroidLockfiles_NoLockfile asserts no-op when no lockfile exists.
